import { chromium, expect } from '@playwright/test';
import { mkdir } from 'node:fs/promises';
const dir = '.taste-skill/states'; await mkdir(dir, { recursive: true });
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1280, height: 900 } });
await page.goto('http://127.0.0.1:4174/');
await page.getByRole('button', { name: 'Ver el ejemplo' }).click();
await page.screenshot({ path: `${dir}/example.png` });
await page.getByRole('button', { name: 'Volver a las instrucciones' }).click();
await page.getByRole('button', { name: 'Ayuda', exact: true }).click();
await page.screenshot({ path: `${dir}/help.png` });
await page.goto('http://localhost:4173/laboratorio.html');
await page.getByText('Herramientas de desarrollo', { exact: true }).click();
await page.getByRole('combobox').selectOption('network');
await page.getByRole('button', { name: 'Crear sesión sintética' }).click();
const frame = page.frameLocator('iframe');
await frame.getByRole('button', { name: 'Comenzar', exact: true }).click();
await frame.locator('canvas').waitFor();
const child = page.frames().find(f => f.url().startsWith('http://127.0.0.1:4173/'));
await expect.poll(() => child.evaluate(async () => {
  const db = await new Promise(resolve => { const r = indexedDB.open('kudlab-play-runtime'); r.onsuccess = () => resolve(r.result); });
  const trials = await new Promise(resolve => { const r = db.transaction('trials').objectStore('trials').getAll(); r.onsuccess = () => resolve(r.result); });
  db.close(); return trials.some(t => t.value.presentedAtMs !== null);
})).toBe(true);
await page.locator('iframe').screenshot({ path: `${dir}/running.png` });
await frame.getByRole('button', { name: 'Terminar actividad' }).click();
await frame.getByRole('button', { name: 'Sí, terminar' }).click();
await frame.getByRole('heading', { name: 'Falta enviar tus resultados', exact: true }).waitFor();
await page.locator('iframe').screenshot({ path: `${dir}/pending.png` });
await page.getByRole('combobox').selectOption('normal');
await frame.getByRole('button', { name: 'Reintentar envío' }).click();
await frame.getByRole('heading', { name: 'Tus resultados se guardaron', exact: true }).waitFor();
await page.locator('iframe').screenshot({ path: `${dir}/saved.png` });
await page.setViewportSize({ width: 390, height: 844 });
await page.goto('http://localhost:4173/demo.html');
const mobile = page.frameLocator('iframe');
await mobile.getByRole('button', { name: 'Comenzar', exact: true }).waitFor();
await page.locator('iframe').screenshot({ path: `${dir}/mobile-instructions.png` });
await mobile.getByRole('button', { name: 'Comenzar', exact: true }).click();
await mobile.locator('.countdown').filter({ hasText: '3' }).waitFor();
await page.locator('iframe').screenshot({ path: `${dir}/mobile-countdown.png` });
await mobile.locator('canvas').waitFor({ state: 'visible' });
const mobileChild = page.frames().find(f => f.url().startsWith('http://127.0.0.1:4173/'));
await expect.poll(() => mobileChild.evaluate(async () => {
  const db = await new Promise(resolve => { const r = indexedDB.open('kudlab-play-runtime'); r.onsuccess = () => resolve(r.result); });
  const trials = await new Promise(resolve => { const r = db.transaction('trials').objectStore('trials').getAll(); r.onsuccess = () => resolve(r.result); });
  db.close(); return trials.some(t => t.value.presentedAtMs !== null);
})).toBe(true);
await page.locator('iframe').screenshot({ path: `${dir}/mobile-running.png` });
await browser.close();
console.log(`Capturas reales de estados: ${dir}`);
